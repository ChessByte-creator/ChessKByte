import fs from "node:fs";
import SQLiteESMFactory from "wa-sqlite/dist/wa-sqlite.mjs";
import * as SQLite from "wa-sqlite";
import { EcDatabase } from "./ec-bundle.mjs";
const path = "/tmp/ec-big-idx.db3"; const fd = fs.openSync(path, "r"); let bytes = 0;
const reader = { size: fs.statSync(path).size, read(o, l) { const b = Buffer.alloc(l); const n = fs.readSync(fd, b, 0, l, o); bytes += n; return new Uint8Array(b.buffer, b.byteOffset, n); } };
const sqlite3 = SQLite.Factory(await SQLiteESMFactory({ wasmBinary: fs.readFileSync("/tmp/proto/node_modules/wa-sqlite/dist/wa-sqlite.wasm") }));
const T = async (label, fn) => { const t = Date.now(), b = bytes; const r = await fn(); console.log(label.padEnd(46), String(Date.now() - t).padStart(6), "ms", ((bytes - b) / 1e6).toFixed(1).padStart(7), "MB", Array.isArray(r) ? `(${r.length})` : ""); return r; };
const db = await EcDatabase.open(sqlite3, reader, "b.db3");
console.log("indexados:", db.info.indexed.join(","));
const m = await T("ids 'magnus' (prefixo, minúsculo)", () => db.ids("players", "magnus"));
const m2 = await T("ids 'Magnus' ", () => db.ids("players", "Magnus"));
await T("ids 'test' (meio do nome → LIKE)", () => db.ids("players", "agnus_T"));
const rare = await db.ids("players", "Player000777");
console.log("ids raro:", rare);
const viaIdx = await T("página Magnus via índice (25)", () => db.pageByPlayerIndex({ playerIds: m2 }, 0, 25));
const viaScan = await T("página Magnus por varredura (25)", () => db.page({ playerIds: m2 }, 0, 600000, 25));
console.log("mesmo resultado:", JSON.stringify(viaIdx.map(r=>r.id)) === JSON.stringify(viaScan.map(r=>r.id)));
const next = await T("2ª página via índice (cursor)", () => db.pageByPlayerIndex({ playerIds: m2 }, viaIdx[24].id, 25));
console.log("2ª começa depois da 1ª:", next[0].id > viaIdx[24].id);
await T("jogador raro via índice (25)", () => db.pageByPlayerIndex({ playerIds: rare }, 0, 25));
await T("raro + elo>=2400 via índice (resíduo)", () => db.pageByPlayerIndex({ playerIds: rare, minElo: 2400 }, 0, 25));
